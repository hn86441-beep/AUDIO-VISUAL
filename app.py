DIAZ_CINTAS_FRAMEWORK = {
    "القيود الشكلية (Formal/Technical Constraints)": [
        ("القيد الزمني (Temporal)", "مدة ظهور الترجمة على الشاشة يجب أن تتيح للمشاهد قراءتها والمشاهدة معًا (عادة 1-6 ثوانٍ للسطر)."),
        ("القيد المكاني (Spatial)", "عدد الأحرف المسموح به لكل سطر (عادة 37-42 حرفًا لاتينيًا، ويختلف حسابه في الصينية لأنها رمزية-مقطعية)."),
        ("قاعدة السطرين (Two-line rule)", "لا يتجاوز السترجة عادة سطرين في آنٍ واحد على الشاشة."),
    ],
    "القيود اللغوية-النصية (Linguistic-Textual Constraints)": [
        ("التماسك النصي (Cohesion)", "الحفاظ على الروابط المنطقية بين الجمل رغم التكثيف أو الحذف."),
        ("نقل السجل اللغوي (Register)", "الحفاظ على مستوى اللغة (فصيح/عامي/ديني) عبر اختيارات معجمية مكافئة."),
        ("العناصر الثقافية (Culture-specific items)", "التعامل مع الأسماء، الأعلام، والمفاهيم الدينية/الشعبية التي لا مقابل مباشر لها."),
    ],
}

def ai_assistant_reply(user_text: str, df: pd.DataFrame) -> str:
    """
    مساعد أكاديمي قائم على قواعد (Rule-based) مصمَّم للإجابة عن:
    (1) أسئلة نظرية AVT بالتفصيل (جوتليب، ديريز-ريمايل، وغيرهما)،
    (2) إحصائيات المدوّنة الحالية،
    (3) أفكار وخطط كتابة للأطروحة،
    (4) أسئلة عامة أو متعلقة بالمسلسل، مع الإفصاح دومًا عن كونه مساعدًا
        قاعديًا لا نموذج ذكاء اصطناعي كامل، تفاديًا لأي انطباع خاطئ بموثوقية مطلقة.
    """
    text = user_text.strip()

    # ------------------- شرح تفصيلي كامل: جوتليب -------------------
    if any(k in text for k in ["جوتليب", "gottlieb", "استراتيجيات جوتليب"]):
        lines_out = ["📚 **استراتيجيات جوتليب العشر للترجمة السمعبصرية (Gottlieb, 1992)** — "
                     "وهي الإطار الأنسب لترجمة الشاشة تحديدًا، ويُنصح باعتمادها عمودًا فقريًا لجدول مدوّنتك:"]
        for s in GOTTLIEB_STRATEGIES_DETAILED:
            lines_out.append(
                f"**{s['name']}**\n"
                f"- التعريف: {s['desc']}\n"
                f"- مثال توضيحي: {s['example']}\n"
                f"- كيف تستفيد منها في الأطروحة: {s['thesis_tip']}\n"
            )
        lines_out.append(
            "💡 نصيحة عامة: بعد إدخال مشاهدك الحقيقية، احسب نسبة كل استراتيجية من هذه العشر، "
            "وناقش في فصل النتائج أيها ارتبط أكثر بالمضمون الديني/الشعبي الخاص بالمسلسل."
        )
        return "\n".join(lines_out)

    # ------------------- شرح تفصيلي كامل: ديريز/دياز-سينتاس -------------------
    if any(k in text for k in ["ديريز", "دياز", "diaz", "díaz", "remael", "ريمايل"]):
        lines_out = ["📚 **إطار Díaz-Cintas & Remael (2007) لقيود ترجمة الشاشة** — "
                     "الأنسب لتحليل فئة 'التحديات التقنية' في جدولك:"]
        for category, items in DIAZ_CINTAS_FRAMEWORK.items():
            lines_out.append(f"**{category}**")
            for name, desc in items:
                lines_out.append(f"- {name}: {desc}")
            lines_out.append("")
        lines_out.append(
            "💡 نصيحة للأطروحة: اربط كل حالة حذف/تكثيف في مدوّنتك بأحد هذه القيود تحديدًا "
            "(زمني، مكاني، أو ثقافي-لغوي) بدل الاكتفاء بوصفها 'صعبة الترجمة' بشكل عام — "
            "هذا يمنح تحليلك دقة منهجية أعلى ويُسهّل مناقشتك أمام لجنة المناقشة."
        )
        return "\n".join(lines_out)

    # ------------------- أسئلة عن نظريات أخرى -------------------
    for key, note in AI_THEORY_NOTES.items():
        if key in text:
            return f"📚 **{key}**: {note}"

    # ------------------- طلب إحصائية سريعة -------------------
    if any(k in text for k in ["إحصائ", "نسبة", "توزيع", "كم عدد"]):
        if len(df) == 0:
            return "لا توجد بيانات بعد في المدوّنة (Corpus) لتحليلها. أضف مشاهدك الحقيقية أولًا في صفحة قاعدة البيانات."
        top_strategy = df["استراتيجية الترجمة"].value_counts().idxmax()
        top_challenge = df["نوع التحدي"].value_counts().idxmax()
        return (
            f"📊 بناءً على {len(df)} مثالًا مُسجَّلًا حاليًا:\n\n"
            f"- الاستراتيجية الأكثر استخدامًا: **{top_strategy}**\n"
            f"- التحدي الأكثر تكرارًا: **{top_challenge}**\n\n"
            "يمكنك مراجعة صفحة 'لوحة الإحصائيات' لرؤية الرسوم البيانية الكاملة والملخص الجاهز للنسخ."
        )

    # ------------------- خطة/هيكلة فصل -------------------
    if any(k in text for k in ["خطة", "هيكل", "فصل", "كيف أكتب", "منهجية"]):
        return (
            "✍️ **مقترح لهيكلة الفصل التحليلي:**\n\n"
            "1) تمهيد نظري موجز عن الترجمة السمعبصرية (AVT) وخصائصها.\n"
            "2) عرض تصنيف الاستراتيجيات المعتمد (جوتليب أساسًا، وديريز-ريمايل للقيود التقنية).\n"
            "3) تحليل كمي: نسب استخدام كل استراتيجية عبر الحلقات المختارة.\n"
            "4) تحليل كيفي: نماذج مختارة (مشاهد دينية، مشاهد عامية، مشاهد رعب).\n"
            "5) تصنيف التحديات (لغوية/ثقافية/دينية/تقنية) مع أمثلة موازية عربي-صيني.\n"
            "6) مناقشة النتائج في ضوء ثنائية الاستئناس/التغريب عند فينوتي.\n"
            "7) خاتمة الفصل وربطها بإشكالية الأطروحة العامة.\n\n"
            "💡 فكرة إبداعية: خصّص جدولًا مقارنًا لكل مشهد ديني يوضح كيف عومل "
            "المصطلح الإسلامي (تكييف/تعميم/حذف) — هذا يميّز أطروحتك لأن المسلسل "
            "مشحون بمفردات دينية-شعبية نادرًا ما دُرست في الترجمة نحو الصينية."
        )

    # ------------------- أفكار إبداعية -------------------
    if any(k in text for k in ["فكرة", "أفكار", "زاوية", "إضافة", "إبداع"]):
        return (
            "💡 **أفكار إبداعية لإثراء الأطروحة:**\n\n"
            "- مقارنة نسخة الدبلجة بنسخة السترجة (إن وُجدت) لنفس المشاهد الدينية.\n"
            "- دراسة استقبال الجمهور الصيني عبر تعليقات منصات البث (تحليل خطاب مصغّر).\n"
            "- بناء 'معجم مصغّر' للمصطلحات الدينية والشعبية العربية ومقابلاتها الصينية المقترحة، كملحق للأطروحة.\n"
            "- تتبع تطور استراتيجية الحذف عبر المواسم: هل يتزايد الحذف كلما زادت الكثافة الحوارية؟\n"
            "- مقارنة ذاتية بين مترجمين مختلفين إن توفرت أكثر من نسخة ترجمة للمسلسل.\n"
            "- ربط النتائج الكمية بنظرية 'قواعد الترجمة الابتدائية والثانوية' عند Toury."
        )

    # ------------------- سؤال عام عن المسلسل -------------------
    if any(k in text for k in ["ما وراء الطبيعة", "المسلسل", "الشخصيات", "قصة المسلسل"]):
        return (
            "🎬 «ما وراء الطبيعة» مسلسل سعودي يتناول قصصًا مستقلة كل حلقة حول ظواهر خارقة "
            "(مسّ، سحر، جن، رقية شرعية) ضمن سياق اجتماعي خليجي معاصر، وهو ما يجعله حقلًا خصبًا "
            "لدراستك لأنه مشحون بمفردات دينية وشعبية يصعب أحيانًا إيجاد مقابل مباشر لها في الصينية. "
            "⚠️ ملاحظة أمانة علمية: لا أملك نص الحلقات الفعلي ولا تفاصيل كل شخصية أو حلقة بدقة "
            "موثوقة يمكن الاستشهاد بها أكاديميًا؛ يجب عليك مشاهدة الحلقات بنفسك أو الرجوع لمصدر "
            "رسمي لاستخراج الحوارات الحقيقية التي ستحللها في مدوّنتك."
        )

    # ------------------- ترحيب عام -------------------
    if any(k in text for k in ["مرحبا", "السلام", "أهلا", "hello"]):
        return (
            "أهلًا بك 👋 أنا مساعدك الأكاديمي لتحليل الترجمة السمعبصرية. اسألني عن: تفاصيل "
            "استراتيجيات جوتليب أو ديريز-ريمايل، إحصائيات مدوّنتك الحالية، أفكار إبداعية، "
            "أو مقترح لهيكلة فصل. يمكنك أيضًا لصق أي حوار لأحلل نمطه اللغوي/الديني المحتمل."
        )

    # ------------------- تحليل نصي عام لأي حوار يُلصق -------------------
    if len(text) > 15:
        detected = []
        if any(w in text for w in ["الله", "رب", "دين", "شيخ", "رقية", "جن"]):
            detected.append("مضمون ديني/عقائدي محتمل → قد يندرج تحت 'التوسيع' أو 'الإبدال' عند جوتليب.")
        if any(w in text for w in ["يا خرابي", "والله", "شو", "ليش", "وين"]):
            detected.append("أسلوب عامي/لهجي → قد يتطلب 'إعادة الصياغة' (Paraphrase) عند جوتليب.")
        if len(text) > 120:
            detected.append("النص طويل نسبيًا → احتمال الحاجة إلى 'التكثيف' (Condensation) بسبب قيود الشاشة عند ديريز-ريمايل.")
        if not detected:
            detected.append("لم يظهر نمط لغوي أو ديني واضح؛ يمكن تصنيفه ضمن 'النقل المباشر' أو 'المعادلة الوظيفية'.")
        return (
            "🔎 **تحليل مبدئي للنص المُدخل (اقتراح أولي وليس حكمًا نهائيًا):**\n\n"
            + "\n".join(f"- {d}" for d in detected)
            + "\n\nللإضافة الرسمية لمدوّنتك، استخدم المصنِّف التلقائي في صفحة «قاعدة البيانات»."
        )

    # ------------------- إجابة افتراضية عامة -------------------
    return (
        "لست نموذج ذكاء اصطناعي عامًا مفتوحًا، بل مساعد أكاديمي مبني على قواعد ثابتة متخصص "
        "في الترجمة السمعبصرية. جرّب أن تسألني تحديدًا عن: 'جوتليب' أو 'ديريز' (شرح تفصيلي)، "
        "'إحصائيات'، 'أفكار'، 'خطة'، أو الصق حوارًا عربيًا لأحلل نمطه."
    )

